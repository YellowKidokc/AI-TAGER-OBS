  constructor(classifier, onProgress) {
    this.classifier = classifier;
    this.onProgress = onProgress;
  }
  resolveContext(file, contextProvider) {
    if (!contextProvider) {
      return void 0;
    }
    if (typeof contextProvider === "function") {
      return contextProvider(file);
    }
    if (contextProvider instanceof Map) {
      return contextProvider.get(file.path);
    }
    return contextProvider[file.path];
  }
  /**
   * Process multiple files
   */
  async processFiles(files, types, contextProvider) {
    const results = /* @__PURE__ */ new Map();
    for (const file of files) {
      this.onProgress(file.path, "processing");
      try {
        const context = this.resolveContext(file, contextProvider);
        const result = await this.classifier.classify(file.content, types, file.path, context);
        results.set(file.path, result);
        const counts = {};
        for (const tag of result.tags) {
          counts[tag.type] = (counts[tag.type] || 0) + 1;
        }
        this.onProgress(file.path, "complete", counts);
      } catch (error) {
        this.onProgress(file.path, `error: ${error instanceof Error ? error.message : "Unknown error"}`);
        results.set(file.path, { tags: [], summary: "Classification failed" });
      }
      await new Promise((resolve) => setTimeout(resolve, 500));
    }
    return results;
  }
  /**
   * Estimate total cost for batch processing
   */
  estimateBatchCost(files, types, contextProvider) {
    let totalInputTokens = 0;
    let totalOutputTokens = 0;
    for (const file of files) {
      const context = this.resolveContext(file, contextProvider);
      const estimate = this.classifier.estimateClassification(file.content, types, context);
      totalInputTokens += estimate.inputTokens;
      totalOutputTokens += estimate.estimatedOutputTokens;
    }
    return {
      totalTokens: totalInputTokens + totalOutputTokens,
      estimatedCost: files.reduce((sum, file) => {
        const context = this.resolveContext(file, contextProvider);
        const estimate = this.classifier.estimateClassification(file.content, types, context);
        return sum + estimate.estimatedCost;
      }, 0)
    };
  }
